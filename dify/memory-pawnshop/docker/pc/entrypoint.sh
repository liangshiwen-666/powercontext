#!/usr/bin/env sh
# PowerContext server entrypoint（记忆当铺）
set -eu

export POWERCONTEXT_HOME="${POWERCONTEXT_HOME:-/data}"
export POWERCONTEXT_SERVER_HTTP_HOST="${POWERCONTEXT_SERVER_HTTP_HOST:-0.0.0.0}"
export POWERCONTEXT_SERVER_HTTP_PORT="${POWERCONTEXT_SERVER_HTTP_PORT:-8000}"
export POWERCONTEXT_SERVER_ALLOW_UNAUTHENTICATED_NON_LOOPBACK="${POWERCONTEXT_SERVER_ALLOW_UNAUTHENTICATED_NON_LOOPBACK:-true}"
export POWERCONTEXT_SERVER_DASHBOARD_ENABLED="${POWERCONTEXT_SERVER_DASHBOARD_ENABLED:-true}"

mkdir -p "$POWERCONTEXT_HOME"
if [ -n "${POWERCONTEXT_SERVER_DATABASE_PATH:-}" ]; then
  mkdir -p "$POWERCONTEXT_SERVER_DATABASE_PATH"
fi

# OpenAI 兼容 SDK 凭据：PowerContext 的 embedding 适配器读取 OPENAI_API_KEY
if [ -n "${SILICONFLOW_API_KEY:-}" ] && [ -z "${OPENAI_API_KEY:-}" ]; then
  export OPENAI_API_KEY="$SILICONFLOW_API_KEY"
  export OPENAI_BASE_URL="${POWERCONTEXT_SERVER_INFERENCE_EMBEDDING_BASE_URL:-https://api.siliconflow.cn/v1}"
fi

echo "starting powercontext (database=${POWERCONTEXT_SERVER_DATABASE_KIND:-sqlite}) ..."
exec powercontext server run
